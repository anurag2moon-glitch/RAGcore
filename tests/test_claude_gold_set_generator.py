"""ClaudeGoldSetGenerator: resolves generated questions' bracketed
citations back to real chunk_ids, scopes generation per chapter, drops
hallucinated citations — no API calls, a stub client stands in for
anthropic.Anthropic (same pattern as test_claude_sufficiency_judge.py).
"""

from __future__ import annotations

from pathlib import Path

import pytest

pytest.importorskip("anthropic")

from ragcore.corpus import Corpus
from ragcore.eval.gold_generation import (
    ClaudeGoldSetGenerator,
    _GeneratedQuestion,
    _GoldSetGenerationResult,
)
from tests.fakes import FakeEmbedder, InMemoryStore


class _StubResponse:
    def __init__(self, parsed_output: _GoldSetGenerationResult) -> None:
        self.parsed_output = parsed_output


class _ScriptedMessages:
    def __init__(self, results: list[_GoldSetGenerationResult]) -> None:
        self._results = results
        self.calls: list[dict] = []

    def parse(self, **kwargs):
        self.calls.append(kwargs)
        return _StubResponse(self._results[len(self.calls) - 1])


class _StubClient:
    def __init__(self, results: list[_GoldSetGenerationResult]) -> None:
        self.messages = _ScriptedMessages(results)


def _corpus_with_chunks(md_book: Path) -> Corpus:
    corpus = Corpus(InMemoryStore(dim=8), FakeEmbedder(dim=8))
    corpus.ingest(md_book)
    return corpus


def test_generate_resolves_citation_to_a_real_chunk_id(md_book: Path) -> None:
    corpus = _corpus_with_chunks(md_book)
    result = _GoldSetGenerationResult(
        questions=[
            _GeneratedQuestion(query="What is this chapter about?", answer_chunk_index=1, expected_facts=["fact"])
        ]
    )
    # one call per chapter — md_book has 2 chapters
    client = _StubClient([result, result])
    generator = ClaudeGoldSetGenerator(client=client)

    questions = generator.generate(corpus)

    assert len(questions) == 2
    for q in questions:
        [passage] = q.gold_passages
        assert passage.chunk_ids
        real_chunk_ids = {c.chunk_id for c in corpus.store.all_chunks()}
        assert passage.chunk_ids[0] in real_chunk_ids
        assert q.expected_facts == ("fact",)
        assert q.notes == "synthetic — generated by ClaudeGoldSetGenerator"


def test_generate_drops_a_hallucinated_citation_without_crashing(md_book: Path) -> None:
    corpus = _corpus_with_chunks(md_book)
    result = _GoldSetGenerationResult(
        questions=[_GeneratedQuestion(query="q", answer_chunk_index=9999, expected_facts=[])]
    )
    client = _StubClient([result, result])
    generator = ClaudeGoldSetGenerator(client=client)

    questions = generator.generate(corpus)

    assert questions == []


def test_generate_respects_questions_per_chapter_cap(md_book: Path) -> None:
    corpus = _corpus_with_chunks(md_book)
    result = _GoldSetGenerationResult(
        questions=[
            _GeneratedQuestion(query="q1", answer_chunk_index=1, expected_facts=[]),
            _GeneratedQuestion(query="q2", answer_chunk_index=1, expected_facts=[]),
            _GeneratedQuestion(query="q3", answer_chunk_index=1, expected_facts=[]),
        ]
    )
    client = _StubClient([result, result])
    generator = ClaudeGoldSetGenerator(client=client, questions_per_chapter=1)

    questions = generator.generate(corpus)

    assert len(questions) == 2  # 1 per chapter, 2 chapters


def test_generate_filters_by_source_ids(md_book: Path) -> None:
    corpus = _corpus_with_chunks(md_book)
    result = _GoldSetGenerationResult(questions=[])
    client = _StubClient([result])
    generator = ClaudeGoldSetGenerator(client=client)

    generator.generate(corpus, source_ids=["nonexistent-source"])

    assert client.messages.calls == []  # no chapters matched, no calls made


def test_generated_gold_set_is_directly_usable_with_run_eval(md_book: Path) -> None:
    """The point of resolving to real chunk_ids at generation time: the
    output needs no further authoring step before scoring retrieval."""
    from ragcore.eval.report import run_eval

    corpus = _corpus_with_chunks(md_book)
    all_chunks = corpus.store.all_chunks()
    target_chunk = all_chunks[0]
    chapter_chunks = [c for c in all_chunks if c.meta.context_group_id == target_chunk.meta.context_group_id]
    target_index = next(
        i for i, c in enumerate(chapter_chunks, start=1) if c.chunk_id == target_chunk.chunk_id
    )

    result = _GoldSetGenerationResult(
        questions=[_GeneratedQuestion(query=target_chunk.text, answer_chunk_index=target_index, expected_facts=[])]
    )
    client = _StubClient([result, result])
    questions = ClaudeGoldSetGenerator(client=client).generate(corpus)

    report = run_eval(corpus, questions, k=5)

    assert report.retrieval.recall_at_k > 0  # the exact-text query finds its own source chunk


def test_generated_question_ids_are_unique(md_book: Path) -> None:
    corpus = _corpus_with_chunks(md_book)
    result = _GoldSetGenerationResult(
        questions=[_GeneratedQuestion(query="q", answer_chunk_index=1, expected_facts=[])]
    )
    client = _StubClient([result, result])
    generator = ClaudeGoldSetGenerator(client=client)

    questions = generator.generate(corpus)

    ids = [q.question_id for q in questions]
    assert len(ids) == len(set(ids))
