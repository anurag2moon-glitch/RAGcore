"""Conversation layer: session-scoped transcripts and context-aware query
rewriting, attached in front of an existing Corpus without any change to
retrieval, generation, or verification.

Two entrypoints, both built the same way (append/read Turns from a
TranscriptStore, rewrite via a QueryRewriter, call the unmodified
Corpus.ask()):

- `PersonaChatSession` — a user talking with one persona.
- `DebateSession` — two or more personas addressing a shared transcript,
  each speaking only through their own Corpus.

The transcript is never written into any persona's corpus, concept graph,
or claim store — it lives only in a `TranscriptStore` (in-memory by
default) for the lifetime of one session, and `close()`/`clear_session()`
frees it explicitly. Persona isolation in debate mode is structural (each
turn is generated by looking up exactly one persona's own Corpus from a
`persona_id -> Corpus` mapping) plus one runtime guard: `DebateSession`
refuses construction if two persona_ids resolve to the identical Corpus
instance.

    from ragcore.conversation import (
        Turn,                                          # transcript entry
        TranscriptStore, QueryRewriter,                 # protocols
        InMemoryTranscriptStore, HistoryAwareQueryRewriter,  # defaults
        persona_system_prompt,                          # authoring helper
        PersonaChatSession, DebateSession,               # entrypoints
    )
"""

